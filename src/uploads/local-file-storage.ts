import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import type { FileStorage } from './file-storage.js';

export class LocalFileStorage implements FileStorage {
  private readonly root: string;

  constructor(directory: string) {
    this.root = resolve(directory);
  }

  async save(path: string, bytes: Buffer) {
    const target = this.within(path);
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, bytes);
  }

  async read(path: string) {
    try {
      return await readFile(this.within(path));
    } catch {
      return null;
    }
  }

  // Paths are generated by the API, but never let one point outside the upload folder.
  private within(path: string) {
    const target = resolve(join(this.root, path));
    if (!target.startsWith(`${this.root}/`)) throw new Error('Path outside the upload folder');
    return target;
  }
}
